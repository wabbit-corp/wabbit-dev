def test_settings_templates_place_plugin_builds_under_plugin_management() -> None:
    settings_template_path = _gradle_template_path("settings.gradle.kts.jinja2")
    subproject_settings_template_path = _gradle_template_path("subproject-settings.gradle.kts.jinja2")
    settings_local_template_path = _gradle_template_path("settings.local.gradle.kts.jinja2")

    settings_content = settings_template_path.read_text(encoding="utf-8")
    subproject_settings_content = subproject_settings_template_path.read_text(encoding="utf-8")
    settings_local_content = settings_local_template_path.read_text(encoding="utf-8")

    assert "pluginManagement {" in settings_content
    assert "pluginManagement {" in subproject_settings_content
    assert settings_content.count("mavenCentral()") >= 2
    assert subproject_settings_content.count("mavenCentral()") >= 2
    assert 'includeBuild("{{ plugin_build.build_path }}")' in settings_content
    assert 'includeBuild("{{ plugin_build.build_path }}")' in subproject_settings_content
    assert "dependencySubstitution" in settings_local_content


