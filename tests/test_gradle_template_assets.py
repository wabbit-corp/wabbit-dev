from __future__ import annotations

from pathlib import Path

import pytest

from dev.template_assets import repo_template_path


def _gradle_template_path(template_name: str) -> Path:
    return repo_template_path("gradle-files", template_name)


@pytest.mark.parametrize(
    "template_name",
    [
        "build.gradle.kts.jinja2",
        "settings.gradle.kts.jinja2",
        "settings.local.gradle.kts.jinja2",
        "subproject-build.gradle.kts.jinja2",
        "subproject-build-kmp.gradle.kts.jinja2",
        "subproject-settings.gradle.kts.jinja2",
    ],
)
def test_gradle_templates_mark_generated_files(template_name: str) -> None:
    template_path = _gradle_template_path(template_name)
    content = template_path.read_text(encoding="utf-8")

    assert content.startswith("// Generated by app-wabbit-dev setup. Do not edit by hand.\n")


