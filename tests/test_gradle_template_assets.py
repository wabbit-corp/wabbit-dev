    subproject_settings_template = _gradle_template_path("subproject-settings.gradle.kts.jinja2")

    settings_content = settings_template.read_text(encoding="utf-8")
    subproject_settings_content = subproject_settings_template.read_text(encoding="utf-8")

    assert 'id("org.jetbrains.intellij") version "{{ intellij_gradle_plugin_version }}"' in settings_content
    assert (
        'id("org.jetbrains.intellij.platform") version "{{ intellij_platform_gradle_plugin_version }}"'
        in settings_content
    )
    assert (
        'id("org.jetbrains.intellij.platform.module") version "{{ intellij_platform_gradle_plugin_version }}"'
        in settings_content
    )
    assert 'id("org.jetbrains.intellij") version "{{ intellij_gradle_plugin_version }}"' in subproject_settings_content
    assert (
        'id("org.jetbrains.intellij.platform") version "{{ intellij_platform_gradle_plugin_version }}"'
        in subproject_settings_content
    )
    assert (
        'id("org.jetbrains.intellij.platform.module") version "{{ intellij_platform_gradle_plugin_version }}"'
        in subproject_settings_content
    )


