def setup(
    mode: RepoSetupMode,
    *,
    interactive: bool = True,
    project: str | None = None,
    projects: list[str] | None = None,
    commit_if_setup_only: bool = False,
    json_output: bool = False,
) -> int:
    selected_projects_input = projects if projects is not None else ([project] if project is not None else None)
    if selected_projects_input == []:
        selected_projects_input = None

    payload: JSONObject = {
        "mode": mode.value,
        "requestedTargets": list(selected_projects_input or []),
        "inferredTargets": [],
        "selectedProjectIds": [],
        "projects": [],
        "repoMetadataRootsWritten": [],
        "repoAgentsWritten": [],
        "workspaceGradleRootWritten": False,
        "repoGradleRootsWritten": [],
        "repoDocsRootsWritten": [],
        "localOverlayRootsWritten": [],
        "localOverlayRootsRemoved": [],
        "unexpectedDirectories": [],
        "autoCommit": {
            "requested": commit_if_setup_only,
            "repos": [],
        },
    }

    def project_payload(project_item: Project) -> JSONObject:
        path = project_item.path
        project_id = project_item.project_id
        return {
            "projectId": project_id or project_item.name,
            "path": str(path.resolve()),
            "repoId": project_item.repo_id,
            "type": type(project_item).__name__.removesuffix("Project").lower(),
        }

    def workspace_top_level_dir_name(path: Path, *, workspace_root: Path) -> str | None:
        resolved_path = path.resolve()
        if resolved_path == workspace_root:
            return None
        if not resolved_path.is_relative_to(workspace_root):
            return None
        relative_path = resolved_path.relative_to(workspace_root)
        if not relative_path.parts:
            return None
        return relative_path.parts[0]

    def run() -> int:
        config = load_config()
        workspace_root = (config.workspace_root or Path(".")).resolve()
        effective_selected_projects_input = inferred_project_targets(config, selected_projects_input)
        if selected_projects_input is None and effective_selected_projects_input is not None:
            payload["inferredTargets"] = list(effective_selected_projects_input)

        if effective_selected_projects_input is None:
            selected_project_names = list(config.defined_projects.keys())
        else:
            try:
                from dev.repo_resolution import resolve_project_ids

                resolved_project_ids = resolve_project_ids(config, effective_selected_projects_input)
            except ValueError as ex:
                payload["error"] = str(ex)
                error(contextualize_failure(str(ex), ["setup", *effective_selected_projects_input]))
                return 1
            selected_project_names = toposort_projects(config.defined_projects, target_project=resolved_project_ids)

        payload["selectedProjectIds"] = list(selected_project_names)
        selected_projects = [config.defined_projects[name] for name in selected_project_names]
        payload["projects"] = [project_payload(project_item) for project_item in selected_projects]
        requires_github_api = any(project_item.github_repo is not None for project_item in selected_projects)
        create_ctx_signature = inspect.signature(create_repo_setup_context)
        create_ctx_kwargs: dict[str, Sequence[Project] | bool] = {}
        if "selected_projects" in create_ctx_signature.parameters:
            create_ctx_kwargs["selected_projects"] = selected_projects
        if "require_github_api" in create_ctx_signature.parameters:
            create_ctx_kwargs["require_github_api"] = requires_github_api
        ctx = create_repo_setup_context(config, mode, **create_ctx_kwargs)

        if effective_selected_projects_input is None:
            info(f"Setting up projects in {mode.value} mode")
        else:
            if len(effective_selected_projects_input) == 1:
                target_label = effective_selected_projects_input[0]
            else:
                target_label = ", ".join(effective_selected_projects_input)
            info(f"Setting up {target_label} and its dependencies in {mode.value} mode")

        gradle_projects = [
            project_item for project_item in selected_projects if isinstance(project_item, GradleProject)
        ]
        dotnet_projects = [
            project_item for project_item in selected_projects if isinstance(project_item, DotnetProject)
        ]
        auto_commit_candidates: tuple[SetupAutoCommitRepoCandidate, ...] = ()
        if commit_if_setup_only:
            auto_commit_candidates = _collect_setup_auto_commit_candidates(
                selected_projects,
                workspace_root=workspace_root,
                include_workspace_root=effective_selected_projects_input is None and bool(gradle_projects),
            )
        if gradle_projects:
            if effective_selected_projects_input is None:
                workspace_seed_projects = gradle_projects
                workspace_root_name = config.default_maven_project_group or "workspace"
                payload["workspaceGradleRootWritten"] = True
                _write_gradle_root_files(
                    ctx,
                    root_path=Path("."),
                    root_project_name=workspace_root_name,
                    seed_projects=workspace_seed_projects,
                    write_wrapper=False,
                    write_build=True,
                    include_external_dependencies=mode == RepoSetupMode.LOCAL,
                    write_dependency_substitutions=mode == RepoSetupMode.LOCAL,
                )

            repo_ids_to_write = {
                project_item.repo_id
                for project_item in gradle_projects
                if project_item.repo_id is not None and project_item.effective_gradle_root != Path(".")
            }
            repo_gradle_roots_written: list[str] = []
            for repo_id in sorted(repo_ids_to_write):
                representative_project = next(
                    (
                        defined_project
                        for defined_project in config.defined_projects.values()
                        if isinstance(defined_project, GradleProject) and defined_project.repo_id == repo_id
                    ),
                    None,
                )
                if representative_project is None:
                    continue
                repo_gradle_roots_written.append(str(representative_project.effective_gradle_root.resolve()))
                setup_gradle_repo_root(ctx, representative_project)
            payload["repoGradleRootsWritten"] = repo_gradle_roots_written

        if dotnet_projects:
            repo_dotnet_roots_written: list[str] = []
            repo_ids_to_write = {
                project_item.repo_id
                for project_item in dotnet_projects
                if project_item.repo_id is not None
            }
            for repo_id in sorted(repo_id for repo_id in repo_ids_to_write if repo_id is not None):
                repo_definition = config.defined_repos.get(repo_id)
                if repo_definition is None:
                    continue
                repo_dotnet_roots_written.append(str(repo_definition.path.resolve()))
                setup_dotnet_repo_root(ctx, repo_id)
            payload["repoDotnetRootsWritten"] = repo_dotnet_roots_written

        for setup_project_item in selected_projects:
            setup_project(
                ctx,
                setup_project_item,
                interactive=interactive,
                commit_changes=False,
                allow_push=False,
            )
        repo_ids_to_write_docs = {
            project_item.repo_id
            for project_item in selected_projects
            if project_item.repo_id is not None
        }
        repo_docs_roots_written: list[str] = []
        for repo_id in sorted(repo_ids_to_write_docs):
            root_written = _write_repo_docs_root(ctx, repo_id)
            if root_written is not None:
                repo_docs_roots_written.append(root_written)
        standalone_gradle_docs_roots = {
            project_item.path.resolve()
            for project_item in selected_projects
            if isinstance(project_item, GradleProject)
            and project_item.repo_id is None
            and project_item.effective_gradle_root == project_item.path
        }
        for root_path in sorted(standalone_gradle_docs_roots):
            project_item = next(
                (
                    selected_project
                    for selected_project in selected_projects
                    if isinstance(selected_project, GradleProject)
                    and selected_project.path.resolve() == root_path
                ),
                None,
            )
            if project_item is None:
                continue
            root_written = _write_standalone_gradle_repo_docs_root(ctx, project_item)
            if root_written is not None:
                repo_docs_roots_written.append(root_written)
        payload["repoDocsRootsWritten"] = repo_docs_roots_written
        payload["repoMetadataRootsWritten"] = _write_repo_metadata_files(ctx, selected_projects)
        payload["repoAgentsWritten"] = _write_repo_agents_files(ctx, selected_projects)

        if mode == RepoSetupMode.LOCAL:
            local_overlay_roots_written: list[str] = []
            repo_ids_to_overlay = {
                project_item.repo_id
                for project_item in gradle_projects
                if project_item.repo_id is not None and project_item.effective_gradle_root != Path(".")
            }
            for repo_id in sorted(repo_ids_to_overlay):
                repo_definition = config.defined_repos.get(repo_id)
                if repo_definition is None:
                    continue
                repo_gradle_projects = [
                    defined_project
                    for defined_project in config.defined_projects.values()
                    if isinstance(defined_project, GradleProject) and defined_project.repo_id == repo_id
                ]
                if not repo_gradle_projects:
                    continue
                local_overlay_roots_written.append(str(repo_definition.path.resolve()))
                _write_gradle_local_overlay(
                    ctx,
                    root_path=repo_definition.path,
                    seed_projects=repo_gradle_projects,
                )

            standalone_gradle_projects = [
                project_item
                for project_item in selected_projects
                if isinstance(project_item, GradleProject) and project_item.effective_gradle_root == project_item.path
            ]
            for standalone_project in standalone_gradle_projects:
                local_overlay_roots_written.append(str(standalone_project.path.resolve()))
                _write_gradle_local_overlay(
                    ctx,
                    root_path=standalone_project.path,
                    seed_projects=[standalone_project],
                )
            payload["localOverlayRootsWritten"] = local_overlay_roots_written
        else:
            overlay_roots: set[Path] = set()
            if effective_selected_projects_input is None and gradle_projects:
                overlay_roots.add(Path("."))
            overlay_roots.update(project_item.effective_gradle_root for project_item in gradle_projects)
            payload["localOverlayRootsRemoved"] = [
                str(overlay_root.resolve()) for overlay_root in sorted(overlay_roots)
            ]
            for overlay_root in sorted(overlay_roots):
                _delete_gradle_local_overlay(root_path=overlay_root)

        if commit_if_setup_only:
            auto_commit_results = _auto_commit_setup_repos(
                auto_commit_candidates,
                mode=mode,
                workspace_root=workspace_root,
                openai_key=config.openai_key,
            )
            payload["autoCommit"]["repos"] = [result.to_json() for result in auto_commit_results]
            for result in auto_commit_results:
                match result.status:
                    case "committed":
                        info(f"Auto-committed setup-only changes in {result.repo_root}")
                    case "skipped":
                        info(f"Skipping setup-only auto-commit for {result.repo_root}: {result.message}")
                    case "error":
                        error(f"Setup-only auto-commit failed for {result.repo_root}: {result.message}")
            if any(result.status == "error" for result in auto_commit_results):
                payload["error"] = "One or more setup-only auto-commits failed."
                return 1

        if effective_selected_projects_input is None:
            expected_top_level_dirs = {
                top_level_dir
                for project_item in config.defined_projects.values()
                for top_level_dir in [
                    workspace_top_level_dir_name(project_repo_root(project_item), workspace_root=workspace_root)
                ]
                if top_level_dir is not None
            }
            ignored_dirs = [
                "build",
                ".gradle",
                "gradle",
                ".idea",
                ".git",
                ".idea",
                ".vscode",
                ".venv",
                ".llm",
                ".kotlin",
                ".ipynb_checkpoints",
            ]

            def is_ignored_dir(dir: Path) -> bool:
                return dir.name in ignored_dirs or dir.name.startswith("tmp.")

            unexpected_directories: list[str] = []
            for dir in sorted(Path(".").iterdir()):
                if dir.is_dir() and dir.name not in expected_top_level_dirs and not is_ignored_dir(dir):
                    unexpected_directories.append(str(dir.resolve()))
                    warning(f"Found unexpected directory: {dir}")
            payload["unexpectedDirectories"] = unexpected_directories

        payload["summary"] = {
            "selectedProjectCount": len(selected_project_names),
            "gradleProjectCount": len(gradle_projects),
        }
        info("All projects set up complete.")
        return 0

    output_context = redirect_stdout(sys.stderr) if json_output else nullcontext()
    with output_context:
        exit_code = run()

    if json_output:
        print(json.dumps(payload, indent=2))
    return exit_code


